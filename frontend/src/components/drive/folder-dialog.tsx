"use client";

import * as React from "react";
import { vi } from "@/i18n/vi";
import { bffClient } from "@/lib/client/bff-client";
import { generateActionKey } from "@/lib/format";
import {
  Dialog,
  DialogContent,
  DialogHeader,
  DialogTitle,
  DialogDescription,
  DialogFooter,
} from "@/components/ui/dialog";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { Loader2, AlertCircle } from "lucide-react";

interface FolderDialogProps {
  open: boolean;
  onOpenChange: (open: boolean) => void;
  slot: 1 | 2;
  onFolderCreated: (slot?: 1 | 2) => void;
  returnFocusRef?: React.RefObject<HTMLButtonElement | null>;
}

interface SlotIntention {
  name: string;
  actionKey: string;
}

export function FolderDialog({
  open,
  onOpenChange,
  slot,
  onFolderCreated,
  returnFocusRef,
}: FolderDialogProps) {
  const [folderName, setFolderName] = React.useState("");
  const [loading, setLoading] = React.useState(false);
  const [error, setError] = React.useState<string | null>(null);
  const [actionKey, setActionKey] = React.useState(() => generateActionKey());
  const [uncertainIntentions, setUncertainIntentions] = React.useState<
    Record<number, SlotIntention>
  >({});

  const [prevOpen, setPrevOpen] = React.useState(open);
  if (open !== prevOpen) {
    setPrevOpen(open);
    if (open) {
      setError(null);
      const slotIntention = uncertainIntentions[slot];
      if (slotIntention) {
        setFolderName(slotIntention.name);
        setActionKey(slotIntention.actionKey);
      } else {
        setFolderName("");
        setActionKey(generateActionKey());
      }
    }
  }

  const handleOpenChange = (newOpen: boolean) => {
    if (newOpen) {
      setError(null);
      const slotIntention = uncertainIntentions[slot];
      if (slotIntention) {
        setFolderName(slotIntention.name);
        setActionKey(slotIntention.actionKey);
      } else {
        setFolderName("");
        setActionKey(generateActionKey());
      }
    }
    onOpenChange(newOpen);
  };

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    const trimmed = folderName.trim();

    if (!trimmed) {
      setError("Tên thư mục không được để trống.");
      return;
    }

    if (trimmed.includes("/") || trimmed.includes("\\")) {
      setError("Tên thư mục không được chứa dấu gạch chéo (/ hoặc \\).");
      return;
    }

    const byteLen = new TextEncoder().encode(trimmed).length;
    if (byteLen > 255) {
      setError("Tên thư mục vượt quá giới hạn 255 byte.");
      return;
    }

    setLoading(true);
    setError(null);

    const slotIntention = uncertainIntentions[slot];
    // Resolve this slot's uncertain operation before accepting a different intention.
    // Closing the dialog or editing a DOM field must not discard an unresolved key.
    if (slotIntention && slotIntention.name !== trimmed) {
      setLoading(false);
      setError(vi.drive.folder.unknownOutcome);
      return;
    }
    const effectiveKey = slotIntention?.actionKey ?? actionKey;

    try {
      await bffClient.fetchJson(`/api/bff/drive/connections/${slot}/folders`, {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
          "Idempotency-Key": effectiveKey,
        },
        body: JSON.stringify({ name: trimmed }),
      });
      setUncertainIntentions((prev) => {
        const next = { ...prev };
        delete next[slot];
        return next;
      });
      setActionKey(generateActionKey());
      onFolderCreated(slot);
      onOpenChange(false);
    } catch (err: unknown) {
      const code = (err as { code?: string })?.code;
      const status = (err as { status?: number })?.status;
      // A lost reply or gateway/server failure can follow a committed remote creation.
      // Keep one bounded intention per slot until its result is known.
      const uncertain =
        !status ||
        status >= 500 ||
        code === "FOLDER_OUTCOME_UNKNOWN" ||
        code === "FOLDER_IN_PROGRESS";
      if (uncertain) {
        setUncertainIntentions((prev) => ({
          ...prev,
          [slot]: {
            name: trimmed,
            actionKey: effectiveKey,
          },
        }));
        setError(vi.drive.folder.unknownOutcome);
      } else if (status === 409 && (code === "FOLDER_KEY_EXPIRED" || code === "FOLDER_FAILED")) {
        // Spring proves absent stale intent or FAILED_DEFINITIVE, not merely any 409.
        // Unlock only; a new key is generated by an explicit name edit, never auto-dispatched.
        setUncertainIntentions((prev) => {
          const next = { ...prev };
          delete next[slot];
          return next;
        });
        setError(
          "Hành động tạo thư mục đã bị từ chối dứt khoát. Hãy nhập tên để bắt đầu hành động mới."
        );
      } else if (code === "FOLDER_KEY_CONFLICT") {
        setError(vi.drive.folder.conflict);
      } else {
        setError(vi.drive.errors.generic);
      }
    } finally {
      setLoading(false);
    }
  };

  return (
    <Dialog open={open} onOpenChange={handleOpenChange}>
      <DialogContent
        className="border-slate-800 bg-slate-900 text-slate-100 sm:max-w-md"
        onCloseAutoFocus={(event) => {
          if (returnFocusRef?.current) {
            event.preventDefault();
            returnFocusRef.current.focus();
          }
        }}
      >
        <DialogHeader>
          <DialogTitle>{vi.drive.folder.dialogTitle}</DialogTitle>
          <DialogDescription className="text-slate-400">
            {vi.drive.folder.dialogDesc}
          </DialogDescription>
        </DialogHeader>

        <form onSubmit={handleSubmit} className="space-y-4">
          <div className="space-y-2">
            <Label htmlFor="folder-name" className="text-xs font-medium text-slate-300">
              {vi.drive.folder.nameLabel}
            </Label>
            <Input
              id="folder-name"
              type="text"
              value={folderName}
              onChange={(e) => {
                if (uncertainIntentions[slot]) return;
                if (error && e.target.value !== folderName) {
                  setActionKey(generateActionKey());
                  setError(null);
                }
                setFolderName(e.target.value);
              }}
              placeholder={vi.drive.folder.namePlaceholder}
              maxLength={255}
              disabled={loading}
              readOnly={!!uncertainIntentions[slot]}
              className="bg-slate-950 border-slate-700 text-white placeholder:text-slate-500"
              autoFocus
            />
          </div>

          {error && (
            <div
              role="alert"
              className="flex items-center gap-2 rounded-lg bg-red-950/40 border border-red-800/60 p-3 text-xs text-red-300"
            >
              <AlertCircle className="h-4 w-4 shrink-0 text-red-400" />
              <span>{error}</span>
            </div>
          )}

          <DialogFooter className="gap-2 sm:gap-0">
            <Button
              type="button"
              variant="outline"
              onClick={() => onOpenChange(false)}
              disabled={loading}
              className="border-slate-700 bg-transparent text-slate-300 hover:bg-slate-800"
            >
              {vi.drive.actions.cancel}
            </Button>
            <Button
              type="submit"
              disabled={loading || !folderName.trim()}
              className="bg-blue-600 hover:bg-blue-700 text-white"
            >
              {loading && <Loader2 className="mr-2 h-4 w-4 animate-spin" />}
              {vi.drive.folder.createButton}
            </Button>
          </DialogFooter>
        </form>
      </DialogContent>
    </Dialog>
  );
}
