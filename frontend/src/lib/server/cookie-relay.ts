import "server-only";
import { type NextResponse } from "next/server";
import { serverConfig } from "./config";

export function setSessionCookie(response: NextResponse, sid: string, maxAgeSeconds: number): void {
  response.cookies.set({
    name: serverConfig.sessionCookieName,
    value: sid,
    path: "/",
    httpOnly: true,
    sameSite: "lax",
    secure: false, // Localhost HTTP pilot only
    maxAge: maxAgeSeconds,
  });
}

export function clearSessionCookie(response: NextResponse): void {
  response.cookies.set({
    name: serverConfig.sessionCookieName,
    value: "",
    path: "/",
    httpOnly: true,
    sameSite: "lax",
    secure: false,
    maxAge: 0,
  });
}

export function relaySpringCookie(
  response: NextResponse,
  springSetCookieHeaders: string[],
  allowedCookieName: string,
  targetPath: string
): boolean {
  const matchingHeaders = springSetCookieHeaders.filter((h) =>
    h.startsWith(`${allowedCookieName}=`)
  );

  // Reject duplicate Set-Cookie headers for the same cookie name
  if (matchingHeaders.length !== 1) {
    return false;
  }

  const header = matchingHeaders[0]!;
  const parts = header.split(";").map((p) => p.trim());
  const firstPart = parts[0]!;
  const cookieValue = firstPart.slice(allowedCookieName.length + 1).trim();

  // Validate value is non-empty
  if (!cookieValue) {
    return false;
  }

  let pathCount = 0;
  let validPath = false;
  let httpOnlyCount = 0;
  let sameSiteCount = 0;
  let validSameSite = false;
  let maxAgeCount = 0;
  let validMaxAge = false;
  let invalidAttr = false;

  for (let i = 1; i < parts.length; i++) {
    const part = parts[i]!;
    const lower = part.toLowerCase();

    if (lower === "httponly") {
      httpOnlyCount++;
    } else if (lower.startsWith("path=")) {
      pathCount++;
      const p = part.slice(5).trim();
      if (p === targetPath) {
        validPath = true;
      }
    } else if (lower.startsWith("samesite=")) {
      sameSiteCount++;
      if (lower === "samesite=lax") {
        validSameSite = true;
      }
    } else if (lower.startsWith("max-age=")) {
      maxAgeCount++;
      if (lower === "max-age=300") {
        validMaxAge = true;
      }
    } else if (lower.startsWith("expires=")) {
      // Standard HTTP/1.0 compatibility attribute generated by Spring ResponseCookie
    } else {
      // Any other attribute (Secure, Domain, etc.) is invalid for this localhost HTTP pilot
      invalidAttr = true;
    }
  }

  if (
    invalidAttr ||
    httpOnlyCount !== 1 ||
    pathCount !== 1 ||
    !validPath ||
    sameSiteCount !== 1 ||
    !validSameSite ||
    maxAgeCount !== 1 ||
    !validMaxAge
  ) {
    return false;
  }

  response.cookies.set({
    name: allowedCookieName,
    value: cookieValue,
    path: targetPath,
    httpOnly: true,
    sameSite: "lax",
    secure: false,
    maxAge: 300,
  });

  return true;
}
